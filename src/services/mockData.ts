export function computeBalanceForEmployee(
  employeeId: number,
  leaveRequests: LeaveRequest[],
  policies: LeavePolicy[]
): LeaveBalance {
  const empRequests = leaveRequests.filter((r) => r.employeeId === employeeId);

  const getPolicyAllowance = (type: LeaveType, fallback: number) =>
    policies.find((p) => p.leaveType === type)?.annualAllowance ?? fallback;

  const buildItem = (type: LeaveType, label: string, fallbackTotal: number) => {
    const totalAllowed = getPolicyAllowance(type, fallbackTotal);
    const used = empRequests
      .filter((r) => r.leaveType === type && r.status === LeaveStatus.APPROVED)
      .reduce((sum, r) => sum + r.numberOfDays, 0);
    const pending = empRequests
      .filter((r) => r.leaveType === type && r.status === LeaveStatus.PENDING)
      .reduce((sum, r) => sum + r.numberOfDays, 0);
    return {
      leaveType: type,
      label,
      totalAllowed,
      used,
      pending,
      remaining: Math.max(0, totalAllowed - used),
    };
  };

  return {
    employeeId,
    year: 2026,
    casual: buildItem(LeaveType.CASUAL, 'Casual Leave', 12),
    sick: buildItem(LeaveType.SICK, 'Sick Leave', 10),
    earned: buildItem(LeaveType.EARNED, 'Earned Leave', 18),
    unpaid: buildItem(LeaveType.UNPAID, 'Unpaid Leave', 30),
  };
}
